def test_question_bank_builder_tops_up_and_skips_duplicate_fingerprint() -> None:
    svc = _make_service()
    svc._repo.get_bank_question_summaries.return_value = []
    svc._repo.save_generated_bank_question.return_value = True
    svc._generator.generate_question.side_effect = [
        {
            "question": "What does DNS TTL control?",
            "options": ["Cache lifetime", "Packet size", "TLS cipher", "Subnet mask"],
            "correct_option_index": 0,
            "explanation": "TTL controls resolver cache duration.",
            "difficulty": "easy",
            "points": 1,
            "subtopic": "DNS / TTL",
            "fingerprint": "fp-ttl",
        },
        {
            "question": "What does DNS TTL control?",
            "options": ["Cache lifetime", "Packet size", "TLS cipher", "Subnet mask"],
            "correct_option_index": 0,
            "explanation": "TTL controls resolver cache duration.",
            "difficulty": "easy",
            "points": 1,
            "subtopic": "DNS / TTL",
            "fingerprint": "fp-ttl",
        },
    ]

    result = svc.build_generated_question_bank(
        max_questions=2,
        target_per_combo=2,
        categories=["networking"],
        difficulties=["easy"],
        subtopics_by_category={"networking": ["DNS / TTL"]},
    )

    assert result["created"] == 1
    assert result["skipped_existing"] == 1
    svc._repo.save_generated_bank_question.assert_called_once()
    saved_question = svc._repo.save_generated_bank_question.call_args.args[2]
    assert saved_question["difficulty_band"] == "ai-generated"


def test_clf_import_items_are_foundation_metadata() -> None:
    script_path = Path(__file__).resolve().parents[1] / "dev" / "scrapers" / "import_questions.py"
    spec = importlib.util.spec_from_file_location("import_questions", script_path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    item = module._build_item(
        "BANK#cloud#aws-clf-c02",
        {
            "uuid": "q1",
            "domain": "Domain 2: Security and Compliance",
            "question": "Which service manages AWS user permissions?",
            "options": ["IAM", "S3", "EC2", "Route 53"],
            "correct_option_id": "0",
            "explanation": "IAM manages identities and access.",
            "exam_name": "CLF-C02",
        },
        "aws-clf-c02",
        "cloud",
    )

    assert item["difficulty"] == "easy_medium"
    assert item["difficulty_band"] == "foundation"
    assert item["subtopic"] == "iam"
    assert len(item["fingerprint"]) == 40
