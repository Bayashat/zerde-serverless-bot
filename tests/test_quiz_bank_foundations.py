def _make_service() -> QuizService:
    svc = QuizService.__new__(QuizService)
    svc._generator = MagicMock()
    svc._sender = MagicMock()
    svc._repo = MagicMock()
    return svc


def _bank_item() -> dict:
    return {
        "question": "Which AWS service stores objects?",
        "options": ["S3", "EC2", "IAM", "VPC"],
        "correct_option_id": 0,
        "explanation": "S3 is object storage.",
    }


def test_clf_bank_serves_easy_with_difficulty_specific_queue() -> None:
    svc = _make_service()
    svc._repo.get_question_queue.return_value = []
    svc._repo.get_bank_question_ids.return_value = ["aws-clf-c02::q1"]
    svc._repo.get_bank_question.return_value = _bank_item()

    result = svc._pick_banked_question_for_chat("cloud", "-100123", "easy")

    assert result is not None
    question, remaining = result
    assert question["question"] == "Which AWS service stores objects?"
    assert question["difficulty"] == "easy"
    assert question["points"] == 1
    assert remaining == []
    svc._repo.get_question_queue.assert_called_once_with("cloud", "-100123", "easy")
    svc._repo.get_bank_question_ids.assert_called_once_with(
        "cloud",
        ["aws-clf-c02"],
        allowed_difficulties={"easy"},
    )


